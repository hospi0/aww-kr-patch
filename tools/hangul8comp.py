def _lit(g, pat, x0, y0):
    for dy, row in enumerate(pat):
        for dx, c in enumerate(row):
            if c == '#':
                g[y0 + dy][x0 + dx] = 1


def _rast(g, strokes, x0, y0, w, h):
    """정규화 획을 (x0,y0,w,h) 픽셀 박스에 그린다."""
    def PX(u, span, o):
        return o + int(round(u * (span - 1)))
    for s in strokes:
        if s[0] == 'h':
            _, a, b, y = s
            yy = PX(y, h, y0)
            for x in range(PX(a, w, x0), PX(b, w, x0) + 1):
                g[yy][x] = 1
        elif s[0] == 'v':
            _, a, b, x = s
            xx = PX(x, w, x0)
            for y in range(PX(a, h, y0), PX(b, h, y0) + 1):
                g[y][xx] = 1
        elif s[0] == 'p':
            g[PX(s[2], h, y0)][PX(s[1], w, x0)] = 1
        elif s[0] == 'o':
            # 모서리 뺀 사각 = 8x8에서 ㅇ 을 ㅁ 과 가르는 유일한 방법
            x1, x2, y1, y2 = x0, x0 + w - 1, y0, y0 + h - 1
            for x in range(x1, x2 + 1):
                g[y1][x] = 1
                g[y2][x] = 1
            for y in range(y1, y2 + 1):
                g[y][x1] = 1
                g[y][x2] = 1
            if w >= 3 and h >= 3:
                for cx, cy in ((x1, y1), (x2, y1), (x1, y2), (x2, y2)):
                    g[cy][cx] = 0
        else:
            _, ax, ay, bx, by = s
            x1, y1, x2, y2 = PX(ax, w, x0), PX(ay, h, y0), PX(bx, w, x0), PX(by, h, y0)
            n = max(abs(x2 - x1), abs(y2 - y1)) or 1
            for i in range(n + 1):
                g[y1 + (y2 - y1) * i // n][x1 + (x2 - x1) * i // n] = 1


def _put(g, table, jamo, box):
    x0, y0, w, h = box
    if table is JONG:
        pat = LIT_JONG.get(jamo)
        if pat:
            _lit(g, pat, x0, y0)
            return
    if table is CHO:
        pat = LIT_CHO.get(jamo, {}).get((w, h))
        if pat:
            _lit(g, pat, x0, y0)
            return
    e = table.get(jamo)
    if e is None:
        return
    if isinstance(e, tuple) and e and e[0] == 'PAIR':
        base = table[e[1]]
        hw = max(2, (w - 1) // 2)
        _rast(g, base, x0, y0, hw, h)
        _rast(g, base, x0 + w - hw, y0, hw, h)
    else:
        _rast(g, e, x0, y0, w, h)


JONG = {}       # 받침은 전부 리터럴이라 표 자체는 비어 있다(_put의 분기 키로만 쓴다)


def glyph8(ch):
    """한 음절 -> 8x8 0/1 격자."""
    g = [[0] * 8 for _ in range(8)]
    d = decompose(ch)
    if d is None:
        return g
    cho, jung, jong = d
    comp = COMPLEX.get(jung)
    vt = 'M' if comp else VTYPE[jung]
    # ★가로 7픽셀만 쓴다(col7은 자간). 안 그러면 옆 음절과 획이 붙는다.
    # ★받침은 3줄 준다. 2줄이면 ㅇ/ㅁ/ㅊ 이 통째로 뭉개진다.
    if vt == 'V':
        if jong:
            _put(g, CHO, cho, (0, 0, 4, 4))
            _put(g, JUNG, jung, (4, 0, 3, 5))
            if jong in LIT_JONG7:
                _lit(g, LIT_JONG7[jong], 0, 5)      # 겹받침은 7폭으로 펴야 두 자모가 보인다
            else:
                _put(g, JONG, jong, (1, 5, 5, 3))
        else:
            _put(g, CHO, cho, (0, 1, 4, 6))
            _put(g, JUNG, jung, (4, 0, 3, 8))
    elif vt == 'H':
        if jong:
            _put(g, CHO, cho, (1, 0, 5, 3))
            _put(g, JUNG, jung, (0, 3, 7, 2))
            _put(g, JONG, jong, (1, 5, 5, 3))
        else:
            _put(g, CHO, cho, (1, 0, 5, 4))
            _put(g, JUNG, jung, (0, 4, 7, 4))
    else:
        hj, vj = comp
        if jong:
            _put(g, CHO, cho, (0, 0, 4, 3))
            _put(g, JUNG, vj, (4, 0, 3, 5))
            _put(g, JUNG, hj, (0, 3, 4, 2))
            _put(g, JONG, jong, (1, 5, 5, 3))
        else:
            _put(g, CHO, cho, (0, 0, 4, 4))
            _put(g, JUNG, vj, (4, 0, 3, 8))
            _put(g, JUNG, hj, (0, 4, 4, 3))
    return g


def to_tile(g, ink=0x0F):
    """8x8 0/1 격자 -> 게임 포맷 32바이트(4bpp, 상위 니블=왼쪽)."""
    out = bytearray()
    for y in range(8):
        for x in range(0, 8, 2):
            out.append(((ink if g[y][x] else 0) << 4) | (ink if g[y][x + 1] else 0))
    return bytes(out)
