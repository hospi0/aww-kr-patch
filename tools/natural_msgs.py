def check():
    bad = []
    for jp, kr in NATURAL.items():
        if len(kr) > len(jp):
            bad.append((jp, kr, len(jp), len(kr)))
    return bad


def apply():
    p = os.path.join(ROOT, 'tools', 'ui16_kr.py')
    s = open(p, encoding='utf-8').read()
    n = 0
    for jp, kr in NATURAL.items():
        pat = re.compile(r"('%s':\s*)'[^']*'" % re.escape(jp))
        s2, k = pat.subn(lambda m: m.group(1) + "'%s'" % kr, s)
        if k:
            s = s2
            n += k
        else:
            print('  ⚠️ 키 못 찾음: %r' % jp)
    open(p, 'w', encoding='utf-8').write(s)
    print('%d개 치환' % n)


if __name__ == '__main__':
    sys.stdout.reconfigure(encoding='utf-8')
    bad = check()
    if bad:
        print('★ 길이 위반 %d건 (번역 ≤ 원문 이어야 함)' % len(bad))
        for jp, kr, a, b in bad:
            print('   [%d→%d] %s  →  %s' % (a, b, jp, kr))
    else:
        print('길이 검사 통과 — %d건 전부 원문 길이 이내' % len(NATURAL))
    if '--apply' in sys.argv:
        if bad:
            raise SystemExit('길이 위반이 있어 적용하지 않는다')
        apply()
