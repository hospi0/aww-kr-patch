"""가타카나 -> 한글 음차 (근사).

용도: 소형 폰트 이름표(지명 245개 등)를 한글화했을 때 **고유 음절이 몇 종 필요한지**
      추정으로 말하지 않고 세기 위한 것. 표기법 완전 준수가 목적이 아니다.
"""
BASE = {
    'ア': '아', 'イ': '이', 'ウ': '우', 'エ': '에', 'オ': '오',
    'カ': '카', 'キ': '키', 'ク': '쿠', 'ケ': '케', 'コ': '코',
    'サ': '사', 'シ': '시', 'ス': '스', 'セ': '세', 'ソ': '소',
    'タ': '타', 'チ': '치', 'ツ': '츠', 'テ': '테', 'ト': '토',
    'ナ': '나', 'ニ': '니', 'ヌ': '누', 'ネ': '네', 'ノ': '노',
    'ハ': '하', 'ヒ': '히', 'フ': '푸', 'ヘ': '헤', 'ホ': '호',
    'マ': '마', 'ミ': '미', 'ム': '무', 'メ': '메', 'モ': '모',
    'ヤ': '야', 'ユ': '유', 'ヨ': '요',
    'ラ': '라', 'リ': '리', 'ル': '르', 'レ': '레', 'ロ': '로',
    'ワ': '와', 'ヲ': '오', 'ン': 'ㄴ', 'ヴ': '브',
    'ガ': '가', 'ギ': '기', 'グ': '구', 'ゲ': '게', 'ゴ': '고',
    'ザ': '자', 'ジ': '지', 'ズ': '즈', 'ゼ': '제', 'ゾ': '조',
    'ダ': '다', 'ヂ': '지', 'ヅ': '즈', 'デ': '데', 'ド': '도',
    'バ': '바', 'ビ': '비', 'ブ': '브', 'ベ': '베', 'ボ': '보',
    'パ': '파', 'ピ': '피', 'プ': '프', 'ペ': '페', 'ポ': '포',
}
# 요음: 앞 글자의 자음 + 야/유/요/아/이/에/오
YOON = {'ャ': 'ㅑ', 'ュ': 'ㅠ', 'ョ': 'ㅛ', 'ァ': 'ㅏ', 'ィ': 'ㅣ', 'ゥ': 'ㅜ', 'ェ': 'ㅔ', 'ォ': 'ㅗ'}
CHO_L = list('ㄱㄲㄴㄷㄸㄹㅁㅂㅃㅅㅆㅇㅈㅉㅊㅋㅌㅍㅎ')
JUNG_L = list('ㅏㅐㅑㅒㅓㅔㅕㅖㅗㅘㅙㅚㅛㅜㅝㅞㅟㅠㅡㅢㅣ')
JONG_L = [''] + list('ㄱㄲㄳㄴㄵㄶㄷㄹㄺㄻㄼㄽㄾㄿㅀㅁㅂㅄㅅㅆㅇㅈㅊㅋㅌㅍㅎ')


def compose(cho, jung, jong=''):
    return chr(0xAC00 + CHO_L.index(cho) * 588 + JUNG_L.index(jung) * 28 + JONG_L.index(jong))


def parts(ch):
    c = ord(ch) - 0xAC00
    return CHO_L[c // 588], JUNG_L[(c % 588) // 28], JONG_L[c % 28]


def translit(s):
    out = []
    for ch in s:
        if ch in YOON and out and out[-1] in BASE.values():
            cho, _, _ = parts(out[-1])
            out[-1] = compose(cho, YOON[ch])
        elif ch == 'ッ':                       # 촉음 -> 앞 음절 ㅅ 받침
            if out and out[-1] != 'ㄴ':
                cho, jung, _ = parts(out[-1])
                out[-1] = compose(cho, jung, 'ㅅ')
        elif ch == 'ー':                       # 장음 무시
            continue
        elif ch == 'ン':
            if out and out[-1] not in ('ㄴ',):
                cho, jung, jong = parts(out[-1])
                if not jong:
                    out[-1] = compose(cho, jung, 'ㄴ')
                    continue
            out.append('은')
        elif ch in BASE:
            out.append(BASE[ch])
        elif ch == '·':
            out.append('·')
        else:
            out.append(ch)                    # 숫자·영문·기호는 그대로
    return ''.join(out)
