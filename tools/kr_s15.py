def kanji_unit(name):
    """한자 유닛명 → 한글. 한자가 남으면 None(=규칙 미비, 호출부가 잡는다)."""
    out = name
    for a, b in _KANJI_RULES:
        out = out.replace(a, b)
    if any('一' <= c <= '鿿' for c in out):
        return None
    return out

