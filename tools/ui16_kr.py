def syllables(text):
    return [c for c in text if '가' <= c <= '힣']


def budget():
    uniq = set()
    for kr in LABELS.values():
        uniq.update(syllables(kr))
    return sorted(uniq)


def budget_all():
    """1단계 라벨 + 3단계 메시지 전체 음절 — **라벨 것을 앞에** 둔다.

    앞쪽(확장 슬롯 825~)에 라벨 음절이 그대로 놓이므로 세션8-a 1단계와 배정이 겹치고,
    새로 늘어난 메시지 음절만 뒤(남은 확장 슬롯 + 재사용 슬롯)로 밀린다.
    """
    lab = budget()
    msg = set()
    for kr in MESSAGES.values():
        msg.update(syllables(kr))
    for kr in UNITINFO.values():          # 세션11: 부대정보 라벨 음절도 슬롯 배정(색적력 '색')
        msg.update(syllables(kr))
    for kr in SETTINGS.values():          # 세션11: 설정화면 라벨 음절
        msg.update(syllables(kr))
    base = lab + sorted(msg - set(lab))

    # ── 세션15: 부대정보 타입값 + 16×16 유닛명 한글화 음절을 **맨 뒤에 append** ──
    #   ASC16CG 를 쓰는 다른 빌더(build_typevals·build_unit16)도 이 배정을 그대로 쓴다.
    #   ★반드시 뒤에 붙인다 — 앞에 끼우면 기존 슬롯이 밀려 이미 기록한 텍스트가 전부 깨진다
    #     (세션12 실사고: 슬롯 재배정 = 그 폰트로 인코딩된 모든 텍스트 재기록).
    try:
        import kr_s15 as S
    except ImportError:
        return base
    s15 = set()
    for d in (S.TYPEVAL_WEAPON, S.TYPEVAL_MOVE, S.UNIT16,
              S.FORMATIONS, S.INFO_TITLES,
              S.KANJI_UNITS):                       # 세션15-d: 한자 유닛명 64종
        for kr in d.values():
            s15.update(syllables(kr))
    for kr in S.MISSION16:                          # 세션15-c: 미션 타이틀 66
        s15.update(syllables(kr))
    try:                                            # 세션15-e: 부대명 16×16 381종
        import json as _j, os as _o
        _f = _o.path.join(_o.path.dirname(_o.path.dirname(_o.path.abspath(__file__))),
                          'work', 'force16_names.json')
        if _o.path.exists(_f):
            for kr in _j.load(open(_f, encoding='utf-8')).values():
                s15.update(syllables(kr))
        _f2 = _o.path.join(_o.path.dirname(_o.path.dirname(_o.path.abspath(__file__))),
                           'work', 'katakana_names.json')     # 세션15-f: 가타카나 유닛명
        if _o.path.exists(_f2):
            for kr in _j.load(open(_f2, encoding='utf-8')).values():
                s15.update(syllables(kr))
    except Exception:
        pass

    # ── 세션16: /KEKKA 훈장·특수능력·수여문 음절도 **맨 뒤에 append** ──
    #   KEKKA 는 전역 폰트 ASC16CG 를 쓴다 ⇒ 그 글리프를 여기서 안 만들면
    #   build_kekka_text 가 아무리 잘 써도 **화면에 빈칸/쓰레기**가 뜬다.
    #   (등록부 work/asc16_slots.json 이 배정을 고정하므로 순서는 안정적이다.)
    try:
        import kekka_kr as _K
        for _d in (_K.KR, _K.RESULT):
            for kr in _d.values():
                s15.update(syllables(kr))
    except ImportError:
        pass

    # ── 세션17: /GMDT 훈장·레벨업 풀(사본) 신규 음절도 **맨 뒤에 append** ──
    #   같은 내용이 /KEKKA 에도 있어 세션16이 그쪽만 번역했는데, 화면이 읽는 건 GMDT 다.
    #   신규 번역 3건이 쓰는 음절(출·격 등)이 없으면 build_gmdt_medal 이 인코딩에서 막힌다.
    try:
        import gmdt_medal_kr as _G
        for kr in _G.NEW.values():
            s15.update(syllables(kr))
    except ImportError:
        pass
    return base + sorted(s15 - set(base))


