def all_tables():
    out = {}
    for t in (LABELS, TYPES, MOVES, NATIONS, MESSAGES):
        out.update(t)
    return out


def demand():
    """필요한 한글 음절 집합."""
    s = set()
    for kr in (list(all_tables().values()) + list(JOINED.values())
               + [a + b for a, b in SPLIT.values()]):
        s |= {c for c in kr if '가' <= c <= '힣'}
    return s

