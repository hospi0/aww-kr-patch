def wrap(text, width=WIDTH):
    """평문 → `▶` 줄바꿈 삽입. 폭 초과 단어는 강제 분할(세션13-d 안전망)."""
    out, line = [], ''
    for word in text.split(' '):
        while len(word) > width:                  # 한 단어가 폭을 넘으면 잘라 넣는다
            if line:
                out.append(line)
                line = ''
            out.append(word[:width])
            word = word[width:]
        if not line:
            line = word
        elif len(line) + 1 + len(word) <= width:
            line += ' ' + word
        else:
            out.append(line)
            line = word
    if line:
        out.append(line)
    return '▶'.join(out) + '▶'


def syllables(s):
    return [c for c in s if '가' <= c <= '힣']


