def font(px):
    return ImageFont.truetype(GULIM, px, index=FONT_IDX)


def iso_entries():
    f = open(TRACK1, 'rb')
    pvd = read_sector(f, 16)
    rl = struct.unpack_from('<I', pvd[156:190], 2)[0]
    rs = struct.unpack_from('<I', pvd[156:190], 10)[0]
    return f, {e['path']: e for e in walk(f, rl, rs) if not e['dir']}


def cram_of(state, ofs):
    from vdp1_dump import load
    cram = load(state)['cram']
    out = []
    for i in range(256):
        w = struct.unpack_from('<H', cram, ((ofs + i) % 2048) * 2)[0]
        out.append(((w & 31) * 8, ((w >> 5) & 31) * 8, ((w >> 10) & 31) * 8))
    return out


def tiles_to_linear(data, cw, ch):
    W = cw * 8
    img = bytearray(W * ch * 8)
    for cy in range(ch):
        for cx in range(cw):
            b = (cy * cw + cx) * 64
            for y in range(8):
                row = data[b + y * 8:b + y * 8 + 8]
                o = (cy * 8 + y) * W + cx * 8
                img[o:o + 8] = row
    return img


def linear_to_tiles(img, cw, ch):
    W = cw * 8
    out = bytearray(cw * ch * 64)
    for cy in range(ch):
        for cx in range(cw):
            b = (cy * cw + cx) * 64
            for y in range(8):
                o = (cy * 8 + y) * W + cx * 8
                out[b + y * 8:b + y * 8 + 8] = img[o:o + 8]
    return out


def nearest(pal, rgb, exclude=()):
    best, bi = None, 0
    for i, c in enumerate(pal):
        if i in exclude:
            continue
        d = sum((a - b) ** 2 for a, b in zip(c, rgb))
        if best is None or d < best:
            best, bi = d, i
    return bi


def inpaint(img, W, H, pal, x0, y0, x1, y1):
    """상자 안을 **바깥 테두리 픽셀에서 거리가중 보간**해 지형을 복원한다.

    🐞인덱스 컬러라 평균이 안 된다 ⇒ RGB 로 보간한 뒤 최근접 팔레트 인덱스로 되돌린다.
    ⚠️단 후보를 **팔레트 256색 전체**에서 고르면 원본에 없던 인덱스가 잔뜩 생겨
      BPE 사전이 망가진다(재압축이 원본보다 2,923B 커졌다). ⇒ 후보를 **그 상자
      둘레에 실제로 쓰인 인덱스**로 제한해 바이트 다양성을 원본 수준으로 묶는다.
    """
    ring = []
    for x in range(x0 - 2, x1 + 3):
        for y in (y0 - 2, y0 - 1, y1 + 1, y1 + 2):
            if 0 <= x < W and 0 <= y < H:
                ring.append((x, y, pal[img[y * W + x]]))
    for y in range(y0 - 2, y1 + 3):
        for x in (x0 - 2, x0 - 1, x1 + 1, x1 + 2):
            if 0 <= x < W and 0 <= y < H:
                ring.append((x, y, pal[img[y * W + x]]))
    if not ring:
        return
    cand = sorted(set(img[ry * W + rx] for rx, ry, _ in ring))
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1):
            num = [0.0, 0.0, 0.0]
            den = 0.0
            for rx, ry, c in ring:
                d = (rx - x) ** 2 + (ry - y) ** 2
                w = 1.0 / (d * d + 1e-6)
                den += w
                for k in range(3):
                    num[k] += c[k] * w
            tgt = [n / den for n in num]
            img[y * W + x] = min(
                cand, key=lambda i: sum((a - b) ** 2 for a, b in zip(pal[i], tgt)))


def text_mask(img, W, H, ink=31, shd=17):
    """원본 **글자 픽셀만** 고른 마스크 — 잉크 연결성분 + 그 오른쪽아래 1px 그림자.

    지형·깃발 아이콘도 같은 그림자색(17)을 쓰기 때문에 「인덱스가 17이면 글자」로
    보면 안 된다. 반드시 **잉크에서 출발**해 그림자를 따라간다.
    """
    m = bytearray(W * H)
    for i in range(W * H):
        if img[i] == ink:
            m[i] = 1
            y, x = divmod(i, W)
            if x + 1 < W and y + 1 < H and img[i + W + 1] == shd:
                m[i + W + 1] = 1
    return m


def draw_labels(img, W, H, pal, labels, px, ink, shadow, erase, log=True,
                orig=None, mask=None):
    """원본 지명을 지우고 한글을 흰색+그림자로 그린다.

    ★★**2패스**다 — ①전부 지우고 ②전부 그린다.
      🐞한 라벨씩 「지우고 그리기」를 반복하면, **뒷 라벨의 지우기가 앞 라벨에 이미
        그려둔 한글을 덮어쓴다.** M12·M15 에서 「비르하케임」 지우기가 「아로쿠마」의
        끝 5px 을 지워 「아로쿠ㅁ'」로 보였다(원본 잔재인 줄 알고 한참 헤맸다).
    """
    plan = []
    for lb in labels:
        jp, ko, x0, y0, x1, y1, anc = lb[:7]
        # ★8번째 원소가 있으면 (dx, dy) 미세조정 — 글자만 옮기고 지우기는 따라 넓힌다
        ndx, ndy = lb[7] if len(lb) > 7 else (0, 0)
        f = font(px)
        bb = ImageDraw.Draw(Image.new('L', (1, 1))).textbbox((0, 0), ko, font=f)
        gw, gh = bb[2] - bb[0], bb[3] - bb[1]
        ow = x1 - x0 + 1
        if anc == 'L':
            tx = x0
        elif anc == 'R':
            tx = x1 - gw + 1
        else:
            tx = x0 + (ow - gw) // 2
        ty = y0 + ((y1 - y0 + 1) - gh) // 2
        tx = max(0, min(tx + ndx, W - gw))
        ty = max(0, min(ty + ndy, H - gh - 1))
        # ★★지우기는 **원본 상자 ∪ 한글이 놓일 범위**로 한다.
        #   🐞원본 상자만 지우면, 한글이 더 길 때(소형맵은 7px→12px 라 대부분 그렇다)
        #     칸 밖으로 나간 획이 안 지워진 원본 위에 겹쳐 「아로쿠ㅁ'」처럼 잘려 보인다.
        plan.append((jp, ko, x0, y0, x1, y1, tx, ty, gw, f, gh))
    # ── 패스1: 전부 지우기 ──
    for jp, ko, x0, y0, x1, y1, tx, ty, gw, f, gh in plan:
        erase(img, min(x0, tx), min(y0, ty),
              max(x1, tx + gw - 1), max(y1, ty + gh - 1))
    # ── 패스2: 전부 그리기 ──
    for jp, ko, x0, y0, x1, y1, tx, ty, gw, f, gh in plan:
        ow = x1 - x0 + 1
        bb = ImageDraw.Draw(Image.new('L', (1, 1))).textbbox((0, 0), ko, font=f)
        if log:
            print('   %-10s -> %-8s 원본 %2dpx칸 x%3d~%3d, 한글 %2dpx @x%3d y%3d%s'
                  % (jp, ko, ow, x0, x1, gw, tx, ty,
                     '  ⚠️원본보다 넓다' if gw > ow else ''))
        can = Image.new('L', (W, H), 0)
        ImageDraw.Draw(can).text((tx - bb[0], ty - bb[1]), ko, font=f, fill=255)
        sh = []
        for y in range(H):
            for x in range(W):
                if can.getpixel((x, y)) >= 128:
                    sh.append((x, y))
        for x, y in sh:                      # ★그림자 먼저(오른쪽아래 1px)
            if x + 1 < W and y + 1 < H:
                img[(y + 1) * W + x + 1] = shadow
        for x, y in sh:
            img[y * W + x] = ink
        # ★라벨별 충돌 집계 — 지형·깃발 위에 올라탄 픽셀 수(0=깨끗)
        if orig is not None and mask is not None:
            n = sum(1 for x, y in sh if orig[y * W + x] and not mask[y * W + x])
            if n and log:
                print('      ⚠️%s 가 아이콘·지형 픽셀 %d개를 덮는다' % (ko, n))


def build():
    sys.stdout.reconfigure(encoding='utf-8')
    os.makedirs(DIR_JP, exist_ok=True)
