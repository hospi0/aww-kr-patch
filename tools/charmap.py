CHARS = {}
for base, s in _ROWS.items():
    for i, ch in enumerate(s):
        CHARS[base + i] = ch

# 한자 구간 추가 판독본 (있으면 병합)
_EXT = os.path.join(ROOT, "work", "charmap_ext.json")
if os.path.exists(_EXT):
    for k, v in json.load(open(_EXT, encoding="utf-8")).items():
        CHARS[int(k)] = v

CTRL = {
    0xFFFF: "\n",      # 후보: 줄/레코드 구분
    0xFFFB: "{FB}",
    0xFFFD: "{FD}",
    0xFFFE: "{FE}",
    0xFFFC: "{FC}",
    0xFFFA: "{FA}",
    0xFFF9: "{F9}",
    0xFFF8: "{F8}",
}


def decode_word(v):
    if v in CTRL:
        return CTRL[v]
    if v >= 0xFF00:
        return "{%04X}" % v
    ch = CHARS.get(v)
    if ch is not None:
        return ch
    return "〈%03x〉" % v      # 〈nnn〉 미판독 글리프


def decode(data, off, count):
    out = []
    for i in range(count):
        v = int.from_bytes(data[off + i * 2: off + i * 2 + 2], "big")
        out.append(decode_word(v))
    return "".join(out)
