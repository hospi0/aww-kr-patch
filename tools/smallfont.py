"""8x8 소형 폰트(무기명·HUD 수치용) 코드표.

발견 경위(세션4): 유닛 상세 화면의 무기명은 16x16 ASC16CG가 아니라 하드엣지 8x8 글리프다.
세이브스테이트의 VDP2 VRAM 0x000000에 143글리프가 **2색 타일**로 상주해 있었고
(ASC16CG는 4bpp 안티에일리어싱이라 「2색 타일 연속 구간」 한 가지로 깨끗이 갈렸다),
★조립 규약이 16x16 폰트와 **반대**였다 — 8x8 4bpp, 32 B/글리프, **상위 니블 = 왼쪽**.
16x16 폰트 규약(저니블=왼쪽)으로 읽어서 여태 글자로 안 보였던 것.

텍스트는 **1바이트 = 1글리프**(16x16 계열의 BE16 인덱스와 다름). 종결자는 0x00.
★탁점/반탁점 순서가 ASC16CG와 **반대**다: 여기선 バビブベボ(125~129)가 먼저, パピプペポ(130~134).
  근거 = 「ブソウナシ」(武装ナシ)를 127로 인코딩했을 때만 GMDT/MUSEUM/SAKUSEN/KEKKA에서 히트.
"""
CHARS = {0: ' '}
_seq = (
    "0123456789"
    "ABCDEFGHIJKLMNOPQRSTUVWXYZ"
    "abcdefghijklmnopqrstuvwxyz"
    "アイウエオカキクケコサシスセソタチツテトナニヌネノハヒフヘホマミムメモヤユヨワヲラリルレロンヴ"
    "ガギグゲゴザジズゼゾダヂヅデド"
    "バビブベボパピプペポ"
    "ァィゥェォッャュョ"
)
for _i, _c in enumerate(_seq):
    CHARS[_i + 1] = _c

# 144~ 기호 (시트 육안 판독). 149=㎜, 150=kg 는 합자 글리프.
# ★149(㎜)·150(㎏)은 **합자 글리프 한 칸**이다. 반드시 단일 문자로 적을 것 —
#   'kg' 두 글자로 쓰면 인코더가 k,g 두 칸으로 뱉는다(첫 빌드에서 실제로 터졌다).
_SYM = {
    144: '.', 145: '·', 146: '’', 147: '=', 148: '/', 149: '㎜', 150: '㎏',
    151: '?', 152: '!', 153: '%', 154: 'ー', 155: ':',
    156: 'Ⅰ', 157: 'Ⅱ', 158: 'Ⅲ', 159: 'Ⅳ', 160: 'Ⅴ', 161: 'Ⅵ',
    162: '[', 163: 'Ⅶ', 164: 'Ⅷ', 165: ']', 166: '✕', 167: '✖',
    168: '★', 169: '(', 170: ')', 171: '+',
}
CHARS.update(_SYM)
# 176 이상은 유닛 아이콘 등 그래픽 타일(글자 아님)

REV = {}
for _k, _v in CHARS.items():
    REV.setdefault(_v, _k)


def decode(b, off=0, n=None, stop=True):
    out = []
    i = off
    end = len(b) if n is None else off + n
    while i < end:
        v = b[i]
        if v == 0 and stop:
            break
        out.append(CHARS.get(v, '<%02x>' % v))
        i += 1
    return ''.join(out)


def encode(s):
    return bytes(REV[c] for c in s)
