def to_kr(name):
    """일본어 부대명 → 한글. 일본 문자가 남으면 None."""
    if name in EXACT:
        return EXACT[name]
    out = name
    for a, b in PERSON:
        out = out.replace(a, b)
    for a, b in PLACE:
        out = out.replace(a, b)
    for a, b in UNIT:
        out = out.replace(a, b)
    if re.search(r'[぀-ヿ一-鿿]', out.replace('ー', '')):
        return None
    return out.replace('ー', '-')


def build(names):
    """[(원문, 한글, 미해결)] — names 는 원문 iterable."""
    ok, miss, over = {}, [], []
    for n in names:
        kr = to_kr(n)
        if kr is None:
            miss.append(n)
        elif len(kr) > 8:
            over.append((n, kr, len(kr)))
        else:
            ok[n] = kr
    return ok, miss, over
