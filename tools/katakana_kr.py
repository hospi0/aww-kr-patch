PREFIX_KEEP = ('P・', 'S・', 'G・', 'R・', 'M10', 'M12', 'M36', 'M4', 'M7', 'H75',
               '155㎜', '40㎜', '3m', 'F．')


def to_kr(name):
    """가타카나 유닛명 → 한글(제식기호 유지). 못 풀면 None."""
    out = name
    for jp, kr in sorted(BASE.items(), key=lambda t: -len(t[0])):
        if jp in out:
            out = out.replace(jp, kr)
    for jp, kr in KANJI.items():
        out = out.replace(jp, kr)
    # 가나·한자가 남으면 실패 (`ー`는 장음부호라 남을 일이 없다)
    if any(('぀' <= c <= 'ヿ' and c not in 'ー・') or '一' <= c <= '鿿' for c in out):
        return None
    return out


def build(names):
    ok, miss, over = {}, [], []
    for n in names:
        kr = to_kr(n)
        if kr is None:
            miss.append(n)
        elif len(kr) > 8:
            over.append((n, kr, len(kr)))
        else:
            ok[n] = kr
    return ok, miss, over
