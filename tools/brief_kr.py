def wrap(text, width=WIDTH):
    """평문 → `▶` 줄바꿈. 공백에서 끊고, **width를 넘는 단어는 강제로 쪼갠다**.

    ★강제분할이 없으면 `Ardennes에서`(10칸)처럼 공백 없는 긴 토큰이 화면 밖으로 넘친다
      (세션13-d 실기에서 실제로 넘쳤다). 번역문에서는 그런 조합을 아예 안 만드는 게 우선이고,
      이 분할은 마지막 안전망이다.
    """
    words = []
    for w in text.split(' '):
        while len(w) > width:
            words.append(w[:width])
            w = w[width:]
        words.append(w)
    lines = []
    cur = ''
    for word in words:
        if not cur:
            cur = word
        elif len(cur) + 1 + len(word) <= width:
            cur += ' ' + word
        else:
            lines.append(cur)
            cur = word
    if cur:
        lines.append(cur)
    return '▶'.join(lines) + '▶'

